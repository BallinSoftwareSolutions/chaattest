#!/usr/bin/env python3
"""Build the checked-in C++ catalog from the reviewable UTF-8 translation source."""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
rows = json.loads((root / 'assets/translations.json').read_text())
def literal(value):
    return 'L' + json.dumps(value, ensure_ascii=False)
output = '// Generated by scripts/generate-translations.py; edit assets/translations.json.\n'
for da, (en, sv) in rows.items():
    assert da and en and sv
    output += '{' + ', '.join(map(literal, [da, en, sv])) + '},\n'
(root / 'src/translations.inc').write_text(output)
